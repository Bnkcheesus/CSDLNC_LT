USE PETCAREDB
-- These triggers are meant to testing 
GO
CREATE OR ALTER TRIGGER TG_ThemKhamBenh
ON KHAMBENH
FOR INSERT
AS
BEGIN
	SET NOCOUNT ON
	IF EXISTS (
		SELECT *
	FROM INSERTED i
		JOIN NHANVIEN ON NHANVIEN.MaTKNV = i.MaBS
	WHERE NHANVIEN.ChucVu != 'BSTY'
	)
	BEGIN
		RAISERROR (N'Chỉ bác sĩ thú y mới được phép khám bệnh', 16, 1)
		ROLLBACK TRANSACTION
		RETURN
	END
END
GO
